import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const hash = createHash('sha256');
for (const language of ['en', 'ru']) {
    hash.update(await readFile(new URL(`../public/i18n/${language}.json`, import.meta.url)));
}
const version = hash.digest('hex').slice(0, 16);
await writeFile(
    new URL('../src/content-version.ts', import.meta.url),
    `// Generated by scripts/content-version.mjs; do not edit.\nexport const SITE_CONTENT_VERSION = '${version}';\n`
);
